void render_transformed_shape(float x, float y, float z, float rx, float ry, float rz, float sx, float sy, float sz, int color, float transparency, int shape) {
    unsigned char xy_check = (distanceBetweenPoints(-camera_x, 0, -camera_z,    x,0,z) < maxPartDist);
    unsigned char  z_check = (distanceBetweenPoints(0, -camera_y, 0,            0,y,0) < (maxPartDist/3));
    if ((xy_check && z_check) || (averageSize(sx,sy,sz) > 8)) {
        pushMatrix();
            scale_rotate_translate(sx, sy, sz, rx, ry, rz, x, y, z);
            switch (shape) {
                default:
                    render_cube(color, transparency);
                    break;
                case (0):
                    render_sphere(color, transparency);
                    break;
            }
        popMatrix();
    }
}

void render_cf(CFrame cf, vec3 size, int color, float transparency, int shape)
{
    vec3 p = cf.position();
    vec3 r = cf.toEulerAngles();
    render_transformed_shape(p.x, p.y, p.z, r.x, r.y, r.z, abs(size.x), abs(size.y), abs(size.z), color, transparency, shape);
}

