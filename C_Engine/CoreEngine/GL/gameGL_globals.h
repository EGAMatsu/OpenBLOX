float distanceBetweenPoints(float x1, float y1, float z1, float x2, float y2, float z2) {
    float dx = x2 - x1;
    float dy = y2 - y1;
    float dz = z2 - z1;
    return sqrt(dx * dx + dy * dy + dz * dz);
}

float averageSize(float x, float y, float z) {
    return (x + y + z) / 3.0f;
}

